import 'package:flutter_test/flutter_test.dart';
import 'package:shared_preferences/shared_preferences.dart';
import 'package:scam_fraud/app_state.dart';
import 'package:scam_fraud/models/audit_report.dart';
import 'package:scam_fraud/services/offline_content.dart';
import 'package:scam_fraud/services/pro_access.dart';
import 'package:scam_fraud/services/report_export.dart';
import 'package:scam_fraud/services/dashboard_analytics.dart';
import 'package:scam_fraud/services/scanner.dart';
import 'package:scam_fraud/services/custom_rules.dart';

AuditReport _report({
  String input = 'A sample scan',
  int findingsCount = 1,
}) => AuditReport(
  id: 'pdf-test',
  createdAt: DateTime(2026, 1, 1),
  input: ScanInput(type: ScanInputType.message, value: input),
  riskScore: 70,
  riskLevel: RiskLevel.high,
  executiveSummary: 'A real report summary.',
  findings: [
    for (var i = 0; i < findingsCount; i++)
      Finding(
        title: 'Suspicious request $i',
        severity: FindingSeverity.high,
        explanation:
            'The message applies urgency and requests confidential information. Verify independently before acting.',
        confidence: 'Heuristic indicator',
        evidence: const [
          Evidence(text: 'Reply now', explanation: 'Time pressure is present.'),
        ],
        attackType: 'Social engineering',
        priority: RecommendationPriority.high,
        recommendedAction: 'Do not share secrets.',
      ),
  ],
  recommendations: const [
    Recommendation(
      priority: RecommendationPriority.high,
      title: 'Verify independently',
      why: 'The request is untrusted.',
      steps: ['Open the official app.'],
      expectedOutcome: 'Confirm safely.',
      requiresConfirmation: false,
    ),
  ],
  checks: const [],
  limitations: const [],
  sources: const {AnalysisSource.deterministic},
  aiRan: false,
);

void main() {
  TestWidgetsFlutterBinding.ensureInitialized();

  test('PDF contains generated bytes from the supplied report', () async {
    final bytes = await ReportExport.build(
      _report(),
      options: const ReportOptions(
        title: 'Customized report',
        palette: ReportPalette.ocean,
        detailed: false,
      ),
    );
    expect(bytes.length, greaterThan(500));
    expect(String.fromCharCodes(bytes.take(4)), '%PDF');
    final longReport = await ReportExport.build(
      _report(
        input: 'https://example.test/${List.filled(4000, 'a').join()}',
        findingsCount: 35,
      ),
    );
    expect(longReport.length, greaterThan(bytes.length));
  });

  test(
    'dashboard aggregation deduplicates reports and applies date filters',
    () {
      final report = _report();
      final first = ScanResult(
        input: 'A',
        verdict: 'Dangerous',
        summary: 'x',
        reasons: const [],
        source: 'Rules',
        date: DateTime(2026, 1, 1),
        report: report,
      );
      final duplicate = ScanResult(
        input: 'B',
        verdict: 'Dangerous',
        summary: 'x',
        reasons: const [],
        source: 'Rules',
        date: DateTime(2026, 1, 1),
        report: report,
      );
      final later = ScanResult(
        input: 'C',
        verdict: 'Safe',
        summary: 'x',
        reasons: const [],
        source: 'Rules',
        date: DateTime(2026, 1, 20),
        report: report.copyWith(riskLevel: RiskLevel.low, riskScore: 4),
      );
      final result = DashboardAnalytics.fromScans(
        [first, duplicate, later],
        start: DateTime(2026, 1, 1),
        end: DateTime(2026, 1, 10),
      );
      expect(result.total, 1);
      expect(result.threats, 1);
      expect(result.byType[ScanInputType.message], 1);
      expect(result.dailyActivity.length, 10);
    },
  );

  test('offline pattern and quiz libraries contain categorized content', () {
    expect(
      scamPatterns.map((item) => item.category).toSet(),
      containsAll([
        'Banking',
        'OTP',
        'Payment',
        'WhatsApp impersonation',
        'Job',
        'Investment',
        'Prize and lottery',
        'Phishing',
        'Social engineering',
        'Customer support',
      ]),
    );
    expect(quizLibrary.length, greaterThan(3));
    expect(quizLibrary.every((item) => item.choices.isNotEmpty), isTrue);
  });

  test(
    'custom phrase rule is stored locally and adds a real report finding',
    () async {
      SharedPreferences.setMockInitialValues({});
      final book = CustomRuleBook.instance;
      await book.load();
      final created = await book.add(
        'invoice deposit',
        'Unexpected upfront fee wording.',
        FindingSeverity.high,
      );
      expect(created, isTrue);
      final matched = await book.apply(
        _report(),
        'Pay the invoice deposit immediately.',
      );
      expect(matched.findings.last.category, 'user_defined');
      expect(matched.riskLevel, RiskLevel.high);
      await book.remove(book.rules.single.id);
    },
  );

  test('saved-history opt-out clears report data', () async {
    SharedPreferences.setMockInitialValues({'remember': true});
    final state = AppState();
    await state.load();
    state.addReport(_report());
    state.setSaveChecks(false);
    final prefs = await SharedPreferences.getInstance();
    expect(prefs.containsKey('history'), isFalse);
    expect(prefs.containsKey('reports'), isFalse);
    expect(state.reports, isEmpty);
  });

  test('centralized feature access distinguishes Free, Pro and Ultra', () {
    final access = ProAccess.instance;
    access.setPlanForTest(ProPlan.free);
    expect(access.allows(FeatureAccess.basicText), isTrue);
    expect(access.allows(FeatureAccess.fullPatterns), isFalse);
    access.setPlanForTest(ProPlan.pro);
    expect(access.allows(FeatureAccess.fullPatterns), isTrue);
    expect(access.allows(FeatureAccess.multiplePdf), isTrue);
    expect(access.aiLimit, 10);
    expect(access.pdfLimit, 10);
    access.setPlanForTest(ProPlan.ultra);
    expect(access.allows(FeatureAccess.customRules), isTrue);
    expect(access.aiLimit, isNull);
    expect(access.pdfLimit, isNull);
    access.setPlanForTest(ProPlan.free);
  });

  test('plan usage limits, success counting, persistence and reset', () async {
    SharedPreferences.setMockInitialValues({});
    final access = ProAccess.instance;
    await access.loadUsageForTest();
    await access.clearUsage();

    access.setPlanForTest(ProPlan.free);
    expect(await access.reserveAiRequest(), isFalse);
    expect(await access.reservePdfExport(), isTrue);
    await access.finishPdfExport(succeeded: true);
    expect(await access.reservePdfExport(), isTrue);
    await access.finishPdfExport(succeeded: true);
    expect(await access.reservePdfExport(), isFalse);

    access.setPlanForTest(ProPlan.pro);
    await access.resetDailyUsage();
    await access.resetMonthlyUsage();
    for (var i = 0; i < 10; i++) {
      expect(await access.reserveAiRequest(), isTrue);
      await access.finishAiRequest(succeeded: i != 2);
    }
    expect(access.aiRequestsToday, 9);
    expect(await access.reserveAiRequest(), isTrue);
    await access.finishAiRequest(succeeded: true);
    expect(access.aiRequestsToday, 10);
    expect(await access.reserveAiRequest(), isFalse);

    for (var i = 0; i < 10; i++) {
      expect(await access.reservePdfExport(), isTrue);
      await access.finishPdfExport(succeeded: true);
    }
    expect(await access.reservePdfExport(), isFalse);

    access.setPlanForTest(ProPlan.ultra);
    for (var i = 0; i < 15; i++) {
      expect(await access.reserveAiRequest(), isTrue);
      await access.finishAiRequest(succeeded: true);
      expect(await access.reservePdfExport(), isTrue);
      await access.finishPdfExport(succeeded: true);
    }
    expect(access.aiRequestsToday, 25);
    expect(access.pdfExportsThisMonth, 25);
    await access.loadUsageForTest();
    expect(access.aiRequestsToday, 25);
    expect(access.pdfExportsThisMonth, 25);
    await access.clearUsage();
    expect(access.aiRequestsToday, 0);
    expect(access.pdfExportsThisMonth, 0);
    access.setDebugPlan(ProPlan.free);
    expect(access.plan, ProPlan.free);
    access.setDebugPlan(ProPlan.pro);
    expect(access.plan, ProPlan.pro);
    access.setDebugPlan(ProPlan.ultra);
    expect(access.plan, ProPlan.ultra);
    access.setDebugPlan(ProPlan.free);
    access.setPlanForTest(ProPlan.free);
  });

  test('stale and corrupt usage periods reset safely', () async {
    SharedPreferences.setMockInitialValues({
      'aegis_ai_day': 'not-a-date',
      'aegis_ai_used': -50,
      'aegis_pdf_month': '2000-01-01T00:00:00.000',
      'aegis_pdf_used': 999,
    });
    final access = ProAccess.instance;
    await access.loadUsageForTest();
    expect(access.aiRequestsToday, 0);
    expect(access.pdfExportsThisMonth, 0);

    final prefs = await SharedPreferences.getInstance();
    final now = DateTime.now();
    await prefs.setString(
      'aegis_ai_day',
      DateTime(now.year, now.month, now.day).toIso8601String(),
    );
    await prefs.setInt('aegis_ai_used', 5);
    await prefs.setString(
      'aegis_pdf_month',
      DateTime(now.year, now.month).toIso8601String(),
    );
    await prefs.setInt('aegis_pdf_used', 3);
    await access.loadUsageForTest();
    expect(access.aiRequestsToday, 5);
    expect(access.pdfExportsThisMonth, 3);
    access.setPlanForTest(ProPlan.free);
    await access.clearUsage();
  });

  test(
    'duplicate pending operations are rejected and failures release quota',
    () async {
      SharedPreferences.setMockInitialValues({});
      final access = ProAccess.instance;
      await access.loadUsageForTest();
      await access.clearUsage();
      access.setPlanForTest(ProPlan.pro);

      expect(await access.reserveAiRequest(), isTrue);
      expect(await access.reserveAiRequest(), isFalse);
      await access.finishAiRequest(succeeded: false);
      expect(access.aiRequestsToday, 0);
      expect(await access.reserveAiRequest(), isTrue);
      await access.finishAiRequest(succeeded: true);
      expect(access.aiRequestsToday, 1);

      expect(await access.reservePdfExport(), isTrue);
      expect(await access.reservePdfExport(), isFalse);
      await access.finishPdfExport(succeeded: false);
      expect(access.pdfExportsThisMonth, 0);
      expect(await access.reservePdfExport(), isTrue);
      await access.finishPdfExport(succeeded: true);
      expect(access.pdfExportsThisMonth, 1);
      await access.clearUsage();
      access.setPlanForTest(ProPlan.free);
    },
  );
}
